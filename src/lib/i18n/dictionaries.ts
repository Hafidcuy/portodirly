export const dictionaries = { en, id } satisfies Record<string, DictionaryShape>;

export type Dictionary = DictionaryShape;

/**
 * Dapatkan kamus teks antarmuka sesuai bahasa.
 *
 * Sengaja didefinisikan di modul murni-data ini (bukan `index.ts`) agar
 * komponen client boleh mengimpornya tanpa menarik `next/headers` ke bundle
 * browser — `index.ts` hanya memakai ulang lewat `export *`.
 */
export function dict(lang: Lang): Dictionary {
  return dictionaries[lang];
}

/** Teks bilingual dari database: `{ en: "...", id: "..." }`. */
export type Bilingual = { en: string; id: string };

export type Lang = keyof typeof dictionaries;

export const LANGS = ["en", "id"] as const satisfies readonly Lang[];

/** Nama cookie bahasa — dipakai server (`getLang`) dan client (error page). */
export const LANG_COOKIE = "lang";

export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "id";
}
